# ---------------------------------------------------------------------------
# Corpus completeness meta-test
# ---------------------------------------------------------------------------
class TestCorpusCompleteness:
    """Sanity check: ensure corpus files actually exist before test runs."""

    EXPECTED_MALICIOUS = [
        "eicar_test.txt", "ps1_dropper.ps1", "revshell.sh",
        "polyglot_elf_pe.bin", "xor_stub.bin",
        "xmrig_ua.txt", "xmrig_config.json", "ransomware_note.bat",
    ]
    EXPECTED_CLEAN = [
        "eicar_clean.txt", "ps1_clean.ps1", "revshell_clean.sh",
        "clean_elf.bin", "clean_nops.bin",
        "clean_config.json", "vssadmin_clean.bat",
    ]

    def test_malicious_corpus_present(self):
        for name in self.EXPECTED_MALICIOUS:
            assert (MALICIOUS_DIR / name).exists(), \
                f"Missing malicious sample: {name} — run generate_corpus.py first"

    def test_clean_corpus_present(self):
        for name in self.EXPECTED_CLEAN:
            assert (CLEAN_DIR / name).exists(), \
                f"Missing clean sample: {name} — run generate_corpus.py first"
