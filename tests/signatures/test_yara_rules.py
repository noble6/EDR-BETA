#!/usr/bin/env python3
"""
tests/signatures/test_yara_rules.py
-------------------------------------
Pytest suite: validates every YARA rule in signatures/signatures.yar against
the corpus generated by generate_corpus.py.

Requirements (testing-security-skill):
  * Every YARA rule has at least one triggering sample (true positive)
  * Every YARA rule has at least one non-triggering sample (no false positive)
  * Tests run in isolation — never against production signature/quarantine paths
  * New crashes must produce a regression test before being marked resolved

Install test dependencies:
  pip install pytest yara-python

Run:
  python tests/signatures/generate_corpus.py   # generate corpus first
  pytest tests/signatures/test_yara_rules.py -v
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import List

import pytest
import yara  # pip install yara-python

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
REPO_ROOT       = Path(__file__).parent.parent.parent
SIGNATURES_FILE = REPO_ROOT / "signatures" / "signatures.yar"
CORPUS_ROOT     = Path(__file__).parent
MALICIOUS_DIR   = CORPUS_ROOT / "malicious"
CLEAN_DIR       = CORPUS_ROOT / "clean"

# ---------------------------------------------------------------------------
# Compile rules once for the entire test session
# ---------------------------------------------------------------------------
@pytest.fixture(scope="session")
def compiled_rules() -> yara.Rules:
    assert SIGNATURES_FILE.exists(), f"Signature file not found: {SIGNATURES_FILE}"
    return yara.compile(str(SIGNATURES_FILE))


# ---------------------------------------------------------------------------
# Helper: run YARA scan on file content
# ---------------------------------------------------------------------------
def scan_bytes(rules: yara.Rules, data: bytes) -> List[str]:
    """Return list of matched rule identifiers."""
    matches = rules.match(data=data)
    return [m.rule for m in matches]


# ---------------------------------------------------------------------------
# Rule 1: EICAR_Test_File
# ---------------------------------------------------------------------------
class TestEICARTestFile:
    RULE_ID = "EICAR_Test_File"

    def test_triggers_on_eicar_string(self, compiled_rules):
        sample = (MALICIOUS_DIR / "eicar_test.txt").read_bytes()
        assert self.RULE_ID in scan_bytes(compiled_rules, sample), \
            "EICAR rule must match the standard EICAR test string"

    def test_no_false_positive_on_clean_text(self, compiled_rules):
        sample = (CLEAN_DIR / "eicar_clean.txt").read_bytes()
        assert self.RULE_ID not in scan_bytes(compiled_rules, sample), \
            "EICAR rule must not match a plain text file"


